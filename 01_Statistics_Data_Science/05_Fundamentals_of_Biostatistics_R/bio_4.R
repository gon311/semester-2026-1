setwd("~/KNOU_stat/R_codes")

# CSV 데이터 불러오기
dat0 <- read.csv("biostat_ex_data.csv")

# 데이터 가공 및 파이프 연산자(%>%) 활용을 위한 dplyr 패키지 로드
library(dplyr)

# 변수 범주형(Factor) 변환:
# 범주형(성별, 재발 여부, 병기, 흡연 여부 등)으로 다뤄야 하는 변수들을 한 번에 factor 타입으로 변환
dat1 <- dat0 %>% mutate_at(vars(sex, Recur, stage, smoking,
                                obesity, Recur_1y,
                                post.CA19.9.binary,
                                post.CA19.9.3grp),
                           as.factor)


# ============================================================
# 1. 단일표본 모평균 가설검정 (One-sample t-test)
# ============================================================

# ------------------------------------------------------------
# [문제 1] 양측검정 (Two-sided test)
# 질문: 췌장암 환자의 몸무게 평균이 65kg이라고 할 수 있는가?
# - 귀무가설 (H0): \mu = 65 (몸무게 평균은 65이다)
# - 대립가설 (H1): \mu ≠ 65 (몸무게 평균은 65가 아니다)
# ------------------------------------------------------------

t.test(dat1$weight, mu = 65)

# [결과 해석 및 복습 포인트]
# 1. t = 2.6984, 자유도(df) = 155
# 2. p-value = 0.00774
#    -> p-value가 통상적인 유의수준 \alpha = 0.05보다 작으므로 귀무가설(H0)을 기각.
#    -> 결론: 췌장암 환자의 평균 몸무게는 65kg과 유의미하게 다르다.
# 3. 95% 신뢰구간: [65.84, 70.41] (65가 포함되지 않음)
# 4. 표본평균: 약 68.13kg


# ------------------------------------------------------------
# [문제 2] 단측검정 (One-sided test)
# 질문: 췌장암 환자의 몸무게 평균이 68kg보다 크다고 할 수 있는가?
# - 귀무가설 (H0): \mu = 68 (몸무게 평균은 68이다)
# - 대립가설 (H1): \mu > 68 (몸무게 평균은 68보다 크다)
# ------------------------------------------------------------

# alternative = "greater": 우측 단측검정을 수행할 때 지정하는 옵션
t.test(dat1$weight, mu = 68, alternative = "greater")

# [결과 해석 및 복습 포인트]
# 1. t = 0.10845, 자유도(df) = 155
# 2. p-value = 0.4569
#    -> p-value가 유의수준 0.05보다 훨씬 크므로 귀무가설(H0)을 기각할 수 없음.
#    -> 결론: 췌장암 환자의 평균 몸무게가 68kg보다 크다고 단정할 수 없다.
# 3. 95% 단측 신뢰구간: [66.21, Inf]


# ============================================================
# 2. 단일표본 모비율 가설검정 (One-sample proportion test)
# ============================================================

# ------------------------------------------------------------
# [문제 3-1] 양측검정 - 정규근사방법 (prop.test)
# 질문: 췌장암 환자 중 남성의 비율이 60%라고 할 수 있는가?
# - 귀무가설 (H0): p = 0.6
# - 대립가설 (H1): p ≠ 0.6
# ------------------------------------------------------------

# x: 관심 사건의 수 (남성(sex==1)인 환자의 수)
# n: 전체 관찰 대상 수 (전체 데이터 행 수)
# p: 검정하고자 하는 모비율 (0.6)
prop.test(x = sum(dat1$sex == 1), n = nrow(dat1), p = 0.6)

# [결과 해석 및 복습 포인트]
# 1. X-squared(카이제곱 검정통계량) = 1.6669, df = 1
# 2. p-value = 0.1967
#    -> p-value가 유의수준 0.05보다 크므로 귀무가설(H0)을 기각할 수 없음.
#    -> 결론: 남성의 비율이 60%와 유의미하게 다르다고 볼 수 없다.
# 3. 표본비율: 102/156 ≈ 0.6538 (65.38%)


# ------------------------------------------------------------
# [문제 3-2] 양측검정 - 정확검정/이항검정 (binom.test)
# 질문: 췌장암 환자 중 남성의 비율이 60%라고 할 수 있는가? (Exact Test)
# - 표본 수에 관계없이 이항분포의 확률식으로 정확한 p-value를 산출하는 방법
# ------------------------------------------------------------

binom.test(x = sum(dat1$sex == 1), n = nrow(dat1), p = 0.6)

# [결과 해석 및 복습 포인트]
# 1. 성공 횟수: 102명 / 전체 시행 횟수: 156명
# 2. p-value = 0.191
#    -> 근사법(0.1967)과 유사하게 유의수준 0.05보다 크므로 귀무가설 채택.


# ------------------------------------------------------------
# [문제 4] 단측검정 - 정확검정 (binom.test)
# 질문: 췌장암 환자 중 남성의 비율이 60%보다 크다고 할 수 있는가?
# - 귀무가설 (H0): p = 0.6
# - 대립가설 (H1): p > 0.6
# ------------------------------------------------------------

# alternative = "greater": 우측 단측검정 옵션 적용
binom.test(x = sum(dat1$sex == 1), n = nrow(dat1), p = 0.6, alternative = "greater")

# [결과 해석 및 복습 포인트]
# 1. p-value = 0.0976
#    -> 유의수준 0.05보다 크므로 귀무가설 기각 실패.
#    -> 결론: 남성의 비율이 60%보다 통계적으로 유의하게 크다고 볼 수 없다.
# 2. 95% 단측 신뢰구간: [0.5862, 1.0000]